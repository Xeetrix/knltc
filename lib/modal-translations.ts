/**
 * Universal helper that returns appropriate string for bn, en, or ja
 */
export function trModal(
  language: "bn" | "en" | "ja",
  bn: string,
  en: string,
  ja?: string
): string {
  if (language === "ja") {
    if (ja) return ja;
    if (MODAL_JA_DICT[en]) return MODAL_JA_DICT[en];
    const trimmed = en.trim();
    if (MODAL_JA_DICT[trimmed]) return MODAL_JA_DICT[trimmed];
    return en;
  }
  if (language === "en") return en;
  return bn;
}
